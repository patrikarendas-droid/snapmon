// Old-vs-new combat comparison for the combat-model change (families decide combat; variants layer on top).
// Loads the game code of an older commit (default: build 19, 17bb241) and the current source side by side and prints a
// Markdown report: families of the formerly Spectral/Mutated-natured categories, stat changes per variant, weakness
// changes, rewards, and fixed-seed simulated battles (same hunter, same random numbers) per group.
// Usage: node tools/combat-report.js [old-ref] > docs/review/COMBAT_MODEL_2.md
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), { execSync } = require('child_process');
const ROOT = path.join(__dirname, '..'), REF = process.argv[2] || '17bb241';
const FILES = ['data.js', 'sprites.js', 'parts.js', 'objects.js', 'labels.js', 'lore.js', 'game.js', 'combatlog.js', 'curated.js', 'curated-data.js'];
function game(read) {
  const ctx = { console: { log() {}, warn() {}, error() {} }, Math, Date, JSON, escape, unescape, btoa: s => Buffer.from(s, 'binary').toString('base64'), atob: s => Buffer.from(s, 'base64').toString('binary'), localStorage: { getItem: () => null, setItem() {} } };
  vm.createContext(ctx);
  vm.runInContext(FILES.map(read).join('\n') + ';globalThis.T={OBJECTS,CATEGORY,CATEGORIES,FAMILIES,createMonster,freshState,newBattle,heroTurnStart,heroStrike,enemyTurn,finishBattle,hunterStats,effMult,setRNG:f=>{RNG=f}}', ctx);
  return ctx.T;
}
const OLD = game(f => execSync(`git show ${REF}:src/${f}`, { cwd: ROOT, maxBuffer: 64 << 20 }).toString());
const NEW = game(f => fs.readFileSync(path.join(ROOT, 'src', f), 'utf8'));
const RAR = ['common', 'uncommon', 'rare', 'epic', 'legendary'], VAR = [null, 'spectral', 'mutated', 'shiny'];
const VN = v => ({ null: 'Normal', spectral: 'Spectral', mutated: 'Mutated', shiny: 'Prismatic' })[v];
const EIGHT = ['book', 'cloth', 'mirror', 'clock', 'instrument', 'toy', 'trash', 'bug'];
const seeded = s => () => { s = (s * 16807) % 2147483647; return s / 2147483647; };
const mk = (T, id, r, v, level, seed) => { const S = T.freshState(); S.level = level; const m = T.createMonster(S, { obj: id, rarity: r, variant: v, word: T.OBJECTS[id].name, photo: null, first: false, rng: seeded(seed) }); return m; };
const ids = Object.keys(NEW.OBJECTS);
const out = [];
const p = s => out.push(s);
const pct = x => (x >= 0 ? '+' : '') + (x * 100).toFixed(1) + '%';
const f2 = x => x.toFixed(2);

p(`# Combat model 2 — old vs new (generated by \`node tools/combat-report.js ${REF}\`)\n`);
p(`Old = game code of \`${REF}\` (build 19). New = current source. Same seeds for both. Generated ${new Date().toISOString().slice(0, 10)}.\n`);

// 1. families of the eight categories
p('## 1. Families of the eight formerly Spectral/Mutated-natured categories\n');
p('| Category | Objects | Old combat table | New family (combat = label) |\n|---|---|---|---|');
for (const c of EIGHT) { const n = ids.filter(id => NEW.OBJECTS[id].cat === c).length; p(`| ${NEW.CATEGORY[c].name} | ${n} | ${OLD.CATEGORY[c].fam} | ${NEW.CATEGORY[c].fam} |`); }
const famMismatch = ids.filter(id => { const m = mk(NEW, id, 'rare', 'spectral', 6, 1); return !NEW.FAMILIES[m.fam]; }).length;
p(`\nEvery one of the ${ids.length} objects now fights with its real family in all four variants (objects whose family is not a real family: ${famMismatch}).\n`);

// 2. stats per variant (ratio to the Normal form of the same object, rarity, level, seed)
p('## 2. Stats of each variant relative to the Normal form of the same monster\n');
p('Average over every object × 5 rarities at level 6 (same seed). Old = what build 19 did, new = now.\n');
p('| Variant | HP old → new | ATK old → new | DEF old → new | SPD old → new |\n|---|---|---|---|---|');
for (const v of ['spectral', 'mutated', 'shiny']) {
  const acc = { old: { hp: 0, atk: 0, def: 0, spd: 0 }, new: { hp: 0, atk: 0, def: 0, spd: 0 } }; let n = 0;
  for (const id of ids) for (const r of RAR) {
    for (const [k, T] of [['old', OLD], ['new', NEW]]) { const a = mk(T, id, r, null, 6, 7), b = mk(T, id, r, v, 6, 7); for (const s of ['hp', 'atk', 'def', 'spd']) acc[k][s] += b.stats[s] / a.stats[s]; }
    n++;
  }
  p(`| ${VN(v)} | ${['hp', 'atk', 'def', 'spd'].map(s => `${pct(acc.old[s] / n - 1)} → ${pct(acc.new[s] / n - 1)}`).join(' | ')} |`);
}
p('\nOld Spectral/Mutated numbers are averages because they REPLACED the family table (a Food monster lost its Food stats); new numbers are fixed modifiers on top of the family.\n');

// 3. weaknesses
p('## 3. Weakness / resistance changes\n');
const els = ['slash', 'ballistic', 'arcane', 'shock', 'toxic'];
const prof = (T, m) => els.map(e => T.effMult(m.fam, e));
let wChanged = { normal8: 0, normal8n: 0, spectral: 0, mutated: 0, shiny: 0, normalOther: 0, n: 0 };
for (const id of ids) {
  const is8 = EIGHT.includes(NEW.OBJECTS[id].cat);
  for (const v of VAR) {
    const a = mk(OLD, id, 'rare', v, 6, 3), b = mk(NEW, id, 'rare', v, 6, 3), diff = JSON.stringify(prof(OLD, a)) !== JSON.stringify(prof(NEW, b));
    if (v === null) { if (is8) { wChanged.normal8n++; if (diff) wChanged.normal8++; } else if (diff) wChanged.normalOther++; } else if (diff) wChanged[v]++;
  }
  wChanged.n++;
}
p(`| Group | Monsters whose weaknesses/resistances changed |\n|---|---|`);
p(`| Normal, the eight categories | ${wChanged.normal8} of ${wChanged.normal8n} |`);
p(`| Normal, every other object | ${wChanged.normalOther} of ${wChanged.n - wChanged.normal8n} |`);
for (const v of ['spectral', 'mutated', 'shiny']) p(`| ${VN(v)} (all objects) | ${wChanged[v]} of ${wChanged.n} |`);
p('\nSpectral and Mutated monsters now have exactly their family\'s weaknesses (before: the Spectral table weak to Ballistic+Arcane, resisting Slash+Toxic; the Mutated table weak to Arcane+Shock, resisting Toxic).\n');

// 4. simulated battles
p('## 4. Fixed-seed simulated battles (difficulty)\n');
p('A level-6 hunter with the Rusty Hunter Sword (upgrade 2, Slash) and a level-6 hunter with the Pistol (Ballistic) attack every turn (special when affordable; no items, no capture), 40 turns max, against every 4th object at Common, Rare and Epic. Same random numbers for old and new. Reported: hunter win rate and average turns.\n');
p('| Group | Weapon | Battles | Win rate old → new | Turns old → new | Hunter HP lost old → new |\n|---|---|---|---|---|---|');
function sim(T, id, r, v, weapon, seed) {
  const S = T.freshState(); S.level = 6; S.weapons = { sword: 2, pistol: 2 }; S.equipped = weapon; S.hp = T.hunterStats(S).maxHp;
  const m = mk(T, id, r, v, 6, seed); let s = seed * 7 + 1; const rng = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; };
  T.setRNG(rng); const B = T.newBattle(S, m), hp0 = B.hero.hp; let t = 0;
  for (; t < 40 && !B.over; t++) { const st = T.heroTurnStart(B); if (B.over) break; if (!st.skip) T.heroStrike(B, S, B.hero.energy >= 60, rng); if (!B.over) T.enemyTurn(B, rng); }
  return { win: B.result === 'victory', turns: t, lost: hp0 - B.hero.hp };
}
const groups = [['Normal — the eight categories', id => EIGHT.includes(NEW.OBJECTS[id].cat), null], ['Normal — every other object', id => !EIGHT.includes(NEW.OBJECTS[id].cat), null],
  ['Spectral (all objects)', () => true, 'spectral'], ['Mutated (all objects)', () => true, 'mutated'], ['Prismatic (all objects)', () => true, 'shiny']];
for (const [name, sel, v] of groups) for (const weapon of ['sword', 'pistol']) {
  const acc = { old: { w: 0, t: 0, l: 0 }, new: { w: 0, t: 0, l: 0 } }; let n = 0;
  ids.filter((_, i) => i % 4 === 0).filter(sel).forEach((id, i) => { for (const r of ['common', 'rare', 'epic']) { for (const [k, T] of [['old', OLD], ['new', NEW]]) { const x = sim(T, id, r, v, weapon, i * 31 + r.length); acc[k].w += x.win; acc[k].t += x.turns; acc[k].l += x.lost; } n++; } });
  p(`| ${name} | ${weapon === 'sword' ? 'Sword (Slash)' : 'Pistol (Ballistic)'} | ${n} | ${pct(acc.old.w / n - 0).replace('+', '')} → ${pct(acc.new.w / n).replace('+', '')} | ${f2(acc.old.t / n)} → ${f2(acc.new.t / n)} | ${f2(acc.old.l / n)} → ${f2(acc.new.l / n)} |`);
}

// 5. rewards
p('\n## 5. Rewards for defeating a monster (average over fixed seeds, Rare, not captured)\n');
p('| Variant | Old | New |\n|---|---|---|');
for (const v of VAR) {
  const tot = { old: {}, new: {} }; let n = 0;
  ids.filter((_, i) => i % 6 === 0).forEach((id, i) => { for (const [k, T] of [['old', OLD], ['new', NEW]]) { const S = T.freshState(); S.level = 6; const m = mk(T, id, 'rare', v, 6, i + 5); T.setRNG(seeded(i + 9)); const B = T.newBattle(S, m); B.over = true; B.result = 'victory'; const before = JSON.stringify(S.mats); T.finishBattle(S, B, seeded(i + 11)); for (const x of ['scrap', 'goo', 'ecto', 'prism']) tot[k][x] = (tot[k][x] || 0) + (S.mats[x] || 0) - (JSON.parse(before)[x] || 0); tot[k].coins = (tot[k].coins || 0) + S.coins - T.freshState().coins; } n++; });
  const show = t => ['scrap', 'goo', 'ecto', 'prism', 'coins'].map(x => `${x} ${f2(t[x] / n)}`).join(', ');
  p(`| ${VN(v)} | ${show(tot.old)} | ${show(tot.new)} |`);
}
p('\nFamily material now always follows the real family (Household/Mechanical → Scrap, Organic/Food/Botanical → Goo, Elemental → Ectoplasm); the variant bonus is added on top and listed separately on the results screen (Spectral +2 Ectoplasm, Mutated +3 Goo, Prismatic +1 Prism Shard and double coins).\n');
process.stdout.write(out.join('\n') + '\n');
